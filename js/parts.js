export const PART_IDS = Object.keys(PARTS);
export const EXTERNAL_IDS = PART_IDS.filter((id) => PARTS[id].ext);
export const INTERNAL_IDS = PART_IDS.filter((id) => !PARTS[id].ext);

// Parts a new lineage can use from the start. Everything else comes through
// mutations, by absorbing genes from other cells (horizontal gene transfer),
// or with endosymbiosis.
export const STARTING_UNLOCKS = ['pili', 'transporter', 'chemoreceptor', 'storage', 'thylakoid', 'gasvesicle', 'capsule', 'pigment'];

// What becoming a complex cell (endosymbiosis) makes available.
export const EUKARYOTE_UNLOCKS = ['pseudopod', 'cilia', 'foodvacuole', 'lysosome', 'oralgroove', 'eyespot', 'mitochondrion'];

export const EYE_IDS = PART_IDS.filter((id) => PARTS[id].eye);
export const MAX_EYES = 4;
export const MAX_EXTERNAL = 12;
export const MAX_INTERNAL = 14;

/** Can a cell of this domain use the part at all? */
export function partAllowed(id, domain) {
  const d = PARTS[id].domain;
  return d === 'any' || d === (domain === 'euk' ? 'euk' : 'pro');
}
